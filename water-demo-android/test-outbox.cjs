const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {randomUUID}=require('node:crypto');
const html=fs.readFileSync('public/water-demo.html','utf8');
const functions=html.slice(html.indexOf('  function cacheLedger('),html.indexOf('  function scheduleSync('));
const replies=html.slice(html.indexOf("    if(['ledger-mutated','ledger-saved'].includes(event.data.action))"),html.indexOf("    if(event.data.action==='auth-config')"));
const writes=[],sent=[];
let storageFailure=false;
const context=vm.createContext({crypto:{randomUUID},localStorage:{setItem:(key,value)=>{if(storageFailure)throw Error('disk full');writes.push(JSON.parse(value));}},recordFrame:{contentWindow:{postMessage:message=>sent.push(message)}},ledgerStatus:()=>{},scheduleSync:()=>{},updateMonthTotal:()=>{}});
vm.runInContext(`let cloudRecords=[],pendingRecords=[],activeOperation=null,ledgerOwner='account',editorReady=true,ledgerSaving=false,ledgerLoading=false,pageMutation=false,ledgerRefreshRequested=false;
${functions}
function reply(action,record){const event={data:{action,record}};${replies}}
function state(){return JSON.parse(JSON.stringify({records:visibleLedger(),pending:pendingRecords,cloud:cloudRecords}));}`,context);
const run=code=>vm.runInContext(code,context);
run("cacheLedger([{id:1,amount:10,time:'2026-10-09T00:00:00Z',category:[]}],[]);queueMutation({id:1,amount:20},'update');");
assert.equal(run('state()').records[0].amount,20);
assert.equal(writes.at(-1).pending.length,1);
run('syncLedger();queueMutation({id:1,amount:30},"update");');
assert.equal(run('state()').pending.length,2,'In-flight update cannot be overwritten');
context.response={owner:'account',operationId:sent[0].record.operationId,record:{id:1,amount:20}};
run('reply("ledger-mutated",response);');
assert.equal(run('state()').records[0].amount,30,'Older success must not erase newer edit');
run('queueMutation({id:1},"delete");');
assert.equal(run('state()').records.length,0);
assert.equal(run('state()').pending.length,1,'Undispatched update can merge into delete');
run('ledgerLoading=true;reply("ledger-data",{owner:"account",records:[{id:1,amount:99}]});');
assert.equal(run('state()').records.length,0,'Stale refresh must not resurrect a tombstone');
run('syncLedger();');
const deletion=sent.at(-1);
context.response={owner:'account',operationId:deletion.record.operationId,error:'offline'};
run('reply("ledger-mutated",response);');
assert.equal(run('state()').pending.length,1);
const durable=writes.at(-1);
context.durable=durable;
run('cacheLedger(durable.records,durable.pending);syncLedger();');
assert.equal(run('state()').records.length,0,'Reload preserves failed delete');
context.response={owner:'account',operationId:sent.at(-1).record.operationId,record:{id:1},deleted:true};
run('reply("ledger-mutated",response);');
assert.equal(run('state()').pending.length,0);
assert.equal(run('state()').cloud.length,0);
run('cacheLedger([],[{id:-1,amount:10}]);syncLedger();queueMutation({id:-1,amount:25},"update");queueMutation({id:-1},"delete");');
assert.equal(run('state()').pending[0].amount,10,'Insert payload stays immutable for retry');
assert.equal(run('state()').records.length,0);
const before=run('state()');
storageFailure=true;
assert.throws(()=>run('queueMutation({id:2,amount:1},"update");'),/disk full/);
assert.deepEqual(run('state()'),before,'Failed local persistence must not acknowledge a change');
console.log('PASS durable updates/deletes, in-flight edits, merge, refresh tombstones, failure/reload, immutable inserts, storage failure');
